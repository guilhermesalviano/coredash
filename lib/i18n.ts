const dictionaries: Record<Locale, Dictionary> = { en, "pt-BR": pt };

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "pt-BR" || value === "en";
}

export function detectLocale(stored?: string | null, navigatorLanguage?: string | null): Locale {
  const candidate = (stored || navigatorLanguage || "").trim().toLowerCase();
  if (candidate.startsWith("en")) return "en";
  if (candidate.startsWith("pt")) return "pt-BR";
  return "pt-BR";
}

export function newsMarket(locale: Locale): { hl: string; gl: string } {
  return locale === "en" ? { hl: "en", gl: "us" } : { hl: "pt", gl: "br" };
}

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const table = dictionaries[locale] ?? dictionaries["pt-BR"];
  let text = table[key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function weatherCondition(code: number, locale: Locale): string {
  return WEATHER_CONDITIONS[code]?.[locale]
    ?? (locale === "en" ? "Unknown condition" : "Condição desconhecida");
}

export function relativeHours(hours: number, locale: Locale): string {
  const safe = Math.max(0, hours);
  if (locale === "en") return safe === 1 ? "about 1 hour ago" : `about ${safe} hours ago`;
  return safe === 1 ? "há cerca de 1 hora" : `há cerca de ${safe} horas`;
}

export function errorCopy(code: string | null | undefined, locale: Locale): string {
  return translate(locale, code === "timeout" ? "errorTimeout" : "errorFailed");
}
